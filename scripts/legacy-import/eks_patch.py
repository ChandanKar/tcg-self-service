#!/usr/bin/env python3
"""Data patch for an install loaded from the legacy portal: legacy "cluster" entries become EKS
environments whose node groups are groups (owner's decision, 2026-11-17), and the history times are
corrected to UTC. Rows only: no table, column or index changes. Every statement is guarded, so a file
applied twice changes nothing the second time.

  fix-01-utc-times.sql      history and last-login times: the legacy clock was UTC, not India time
  eks-01-environments.sql   before the EKS sync: EKS environments, "Helper VMs" groups, helper VMs moved,
                            merged legacy entries made inactive, Helper VMs access for their people
  eks-02-nodegroup-access.sql
                            after the EKS sync has created the node-group groups: each legacy entry's
                            people get Operator access to their node groups only

Usage: python eks_patch.py --mapping eks-mapping.json --out <dir>
Then:  fix-01 and eks-01 (app running is fine) -> wait for the EKS sync (5 min) or press "Sync EKS now" in
       System health -> eks-02 -> "Sync EKS now" again registers the registerOnly clusters (admins only).
"""
import argparse
import json
import os
import re
import sys
import uuid

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from convert import uid, sql, jsn, MARK, DEFAULT_ACCOUNT  # noqa: E402

SERVICE_USER = uid('user', 'legacy-import')
IMPORTED_AT = '2026-11-16 16:30:00'   # the legacy data was loaded on staging just after this (UTC)


def env_id(vid):
    return uid('env', str(vid))


def new_env_id(cluster):
    return str(uuid.uuid5(uuid.UUID(uid('eks', 'namespace')), f'env:{cluster}'))


def helper_group_id(cluster):
    return str(uuid.uuid5(uuid.UUID(uid('eks', 'namespace')), f'helper:{cluster}'))


def uuid_from_md5(expr):
    """SQL for a UUID-shaped, deterministic id from an MD5 of expr (for rows made from what is in the DB)."""
    m = f'MD5(CONCAT({expr}))'
    return (f"LOWER(CONCAT_WS('-', SUBSTR({m},1,8), SUBSTR({m},9,4), SUBSTR({m},13,4), "
            f"SUBSTR({m},17,4), SUBSTR({m},21,12)))")


def header(name, what):
    return [f'-- {name}: {what}', '-- Rows only: no table, column or index changes. Generated by scripts/legacy-import/eks_patch.py.',
            'SET NAMES utf8mb4;', "SET time_zone = '+00:00';", 'START TRANSACTION;', '']


def utc_fix():
    out = header('fix-01-utc-times.sql', 'the legacy clock was UTC; the import treated it as India time (5 h 30 too early)')
    flag = "EXISTS (SELECT 1 FROM (SELECT 1 FROM audit_log WHERE details LIKE '% India time)%' LIMIT 1) t)"
    out += [
        '-- Last and previous sign-in times taken from the legacy history (not ones made in the app since).',
        f"UPDATE app_user SET last_login_at = last_login_at + INTERVAL 330 MINUTE\n WHERE legacy_user_id IS NOT NULL AND last_login_at < {sql(IMPORTED_AT)} AND {flag};",
        f"UPDATE app_user SET previous_login_at = previous_login_at + INTERVAL 330 MINUTE\n WHERE legacy_user_id IS NOT NULL AND previous_login_at < {sql(IMPORTED_AT)} AND {flag};",
        '-- The two old portal registrations (their created date came from the same clock).',
        f"UPDATE app_user SET created_at = created_at + INTERVAL 330 MINUTE, updated_at = updated_at + INTERVAL 330 MINUTE\n"
        f" WHERE user_id IN ({sql(uid('registration', '1'))}, {sql(uid('registration', '2'))}) AND {flag};",
        '-- The imported history: time and the note saying which clock it was.',
        "UPDATE audit_log SET created_at = created_at + INTERVAL 330 MINUTE, details = REPLACE(details, ' India time)', ' UTC)')\n"
        f" WHERE details LIKE {sql(MARK + ' (audit #%')} AND details LIKE '% India time)%';",
        '', 'COMMIT;', '']
    return out


def eks_environments(m):
    out = header('eks-01-environments.sql', 'legacy cluster entries become EKS environments (before the EKS sync)')
    for w in m['wholeCluster']:
        e, cluster, region = env_id(w['legacyVmId']), w['cluster'], w['region']
        out += [f"-- {cluster}: legacy entry #{w['legacyVmId']} becomes the EKS environment; its VMs become \"Helper VMs\".",
                f"UPDATE environment SET service_type = 'EKS', eks_cluster_name = {sql(cluster)},\n"
                f"       metadata = JSON_SET(COALESCE(metadata, '{{}}'), '$.region', {sql(region)}, '$.eksCluster', {sql(cluster)})\n"
                f" WHERE environment_id = {sql(e)} AND service_type = 'EC2';",
                f"UPDATE vm_group SET name = 'helper-vms', display_name = 'Helper VMs',\n"
                f"       description = 'EC2 VMs the legacy portal started with the cluster (control, ops or status VMs)'\n"
                f" WHERE environment_id = {sql(e)} AND name = 'default-group';", '']
    for p in m['perNodeGroup']:
        cluster, region = p['cluster'], p['region']
        nid, hid = new_env_id(cluster), helper_group_id(cluster)
        vids = sorted(p['entries'], key=int)
        envs = ', '.join(sql(env_id(v)) for v in vids)
        name = re.sub('-+', '-', re.sub('[^a-z0-9-]', '-', cluster.lower()))
        meta = {'region': region, 'eksCluster': cluster, 'defaultCloudProvider': 'AWS',
                'mergedLegacyVmIds': [int(v) for v in vids],
                'legacyNodeGroups': {v: p['entries'][v] for v in vids}}
        out += [f"-- {cluster}: one EKS environment for the legacy entries #{', #'.join(vids)} (one per node group).",
                "INSERT INTO environment (environment_id, name, display_name, description, is_active, created_at, updated_at,\n"
                "                         metadata, service_type, eks_cluster_name, aws_account_ref)\n"
                f"SELECT {sql(nid)}, {sql(name)}, {sql(cluster)},\n"
                f"       {sql(f'EKS cluster {cluster}: its node groups are groups. Replaces the legacy entries #' + ', #'.join(vids) + '.')},\n"
                f"       1, UTC_TIMESTAMP(), UTC_TIMESTAMP(), {sql(jsn(meta))}, 'EKS', {sql(cluster)}, {sql(DEFAULT_ACCOUNT)}\n"
                f" WHERE NOT EXISTS (SELECT 1 FROM environment WHERE environment_id = {sql(nid)});",
                "INSERT INTO vm_group (group_id, environment_id, name, display_name, description, sequence_position, created_at, updated_at, metadata)\n"
                f"SELECT {sql(hid)}, {sql(nid)}, 'helper-vms', 'Helper VMs',\n"
                "       'EC2 VMs the legacy portal started with the cluster (control, ops or status VMs)', 1, UTC_TIMESTAMP(), UTC_TIMESTAMP(),\n"
                f"       {sql(jsn({'helperVms': True, 'eksCluster': cluster}))}\n"
                f" WHERE NOT EXISTS (SELECT 1 FROM vm_group WHERE group_id = {sql(hid)});",
                '-- The legacy entries\' VMs (their helper VMs) move into "Helper VMs", numbered in order.',
                f"SET @seq := (SELECT COALESCE(MAX(sequence_position), 0) FROM vm WHERE group_id = {sql(hid)});",
                f"UPDATE vm SET group_id = {sql(hid)}, sequence_position = (@seq := @seq + 1)\n"
                f" WHERE group_id IN (SELECT group_id FROM vm_group WHERE environment_id IN ({envs}))\n"
                " ORDER BY group_id, sequence_position;",
                '-- Their people (and people of shortcuts to them) get access to "Helper VMs" of the new environment.',
                "INSERT INTO environment_access (access_id, environment_id, user_id, access_level, granted_by_user_id, granted_at,\n"
                "                                status, notes, scope_type, scope_id, initiation)\n"
                f"SELECT x.id, {sql(nid)}, x.user_id, 'USER', {sql(SERVICE_USER)}, x.granted_at, 'ACTIVE',\n"
                f"       {sql(f'{MARK}: EKS cluster {cluster}, Helper VMs (legacy entries #' + ', #'.join(vids) + ')')}, 'GROUP', {sql(hid)}, 'DIRECT'\n"
                f"  FROM (SELECT a.user_id, MIN(a.granted_at) AS granted_at, {uuid_from_md5(sql('eks-helper:' + hid + ':') + ', a.user_id')} AS id\n"
                "          FROM environment_access a\n"
                f"         WHERE a.status = 'ACTIVE' AND ((a.scope_type = 'ENVIRONMENT' AND a.environment_id IN ({envs}))\n"
                f"            OR (a.scope_type = 'GROUP' AND a.scope_id IN (SELECT group_id FROM vm_group WHERE environment_id IN ({envs}))))\n"
                "         GROUP BY a.user_id) x\n"
                " WHERE NOT EXISTS (SELECT 1 FROM environment_access e WHERE e.access_id = x.id);",
                '-- The legacy entries become inactive; their own grants and history stay with them.',
                f"UPDATE environment SET is_active = 0,\n"
                f"       metadata = JSON_SET(COALESCE(metadata, '{{}}'), '$.importedInactiveReason', {sql('merged into the EKS environment ' + cluster)},\n"
                f"                           '$.mergedInto', {sql(nid)})\n"
                f" WHERE environment_id IN ({envs}) AND is_active = 1;", '']
    out += ['-- Clusters to register as they are ("Sync EKS now"): an inactive legacy entry with the same name would',
            '-- make the sync think the cluster is already registered, so that entry is renamed "<name>-legacy".']
    for cluster in m.get('registerOnly', []):
        slug = re.sub('-+', '-', re.sub('[^a-z0-9-]', '-', cluster.lower()))
        out += [f"UPDATE environment SET name = {sql(slug + '-legacy')},\n"
                f"       metadata = JSON_SET(COALESCE(metadata, '{{}}'), '$.renamedFrom', name)\n"
                f" WHERE name = {sql(slug)} AND is_active = 0 AND service_type = 'EC2'\n"
                f"   AND NOT EXISTS (SELECT 1 FROM (SELECT 1 FROM environment WHERE name = {sql(slug + '-legacy')}) t);"]
    return out + ['', 'COMMIT;', '']


def nodegroup_access(m):
    out = header('eks-02-nodegroup-access.sql', "each legacy entry's people get their node groups (after the EKS sync)")
    out += ['-- Needs the node-group groups the EKS sync creates (named after the node groups). Run the check',
            '-- at the end: every listed node group must exist, or the sync has not run yet.']
    checks = []
    for p in m['perNodeGroup']:
        cluster, nid = p['cluster'], new_env_id(p['cluster'])
        for vid in sorted(p['entries'], key=int):
            ngs = p['entries'][vid]
            out += [f"-- {cluster}: legacy entry #{vid} -> {', '.join(ngs)}",
                    "INSERT INTO environment_access (access_id, environment_id, user_id, access_level, granted_by_user_id, granted_at,\n"
                    "                                status, notes, scope_type, scope_id, initiation)\n"
                    f"SELECT x.id, {sql(nid)}, x.user_id, 'USER', {sql(SERVICE_USER)}, x.granted_at, 'ACTIVE',\n"
                    f"       CONCAT({sql(f'{MARK}: EKS cluster {cluster}, node group ')}, x.ng, {sql(f' (legacy entry #{vid})')}), 'GROUP', x.group_id, 'DIRECT'\n"
                    f"  FROM (SELECT a.user_id, g.group_id, g.name AS ng, MIN(a.granted_at) AS granted_at,\n"
                    f"               {uuid_from_md5(sql('eks-ng:') + ', g.group_id, ' + sql(':') + ', a.user_id')} AS id\n"
                    "          FROM environment_access a\n"
                    f"          JOIN vm_group g ON g.environment_id = {sql(nid)} AND g.name IN ({', '.join(sql(n) for n in ngs)})\n"
                    f"         WHERE a.status = 'ACTIVE' AND a.scope_type = 'ENVIRONMENT' AND a.environment_id = {sql(env_id(vid))}\n"
                    "         GROUP BY a.user_id, g.group_id, g.name) x\n"
                    " WHERE NOT EXISTS (SELECT 1 FROM environment_access e WHERE e.access_id = x.id);", '']
            checks += [f"SELECT {sql(cluster)}, {sql(n)}, COUNT(*) FROM vm_group WHERE environment_id = {sql(nid)} AND name = {sql(n)}" for n in ngs]
    out += ['COMMIT;', '', '-- Check: every row must say 1 (the node group exists as a group).',
            '\nUNION ALL '.join(checks) + ';', '']
    return out


def main(argv=None):
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument('--mapping', required=True)
    a.add_argument('--out', required=True)
    args = a.parse_args(argv)
    with open(args.mapping, encoding='utf-8') as f:
        m = json.load(f)
    os.makedirs(args.out, exist_ok=True)
    for name, lines in (('fix-01-utc-times.sql', utc_fix()), ('eks-01-environments.sql', eks_environments(m)),
                        ('eks-02-nodegroup-access.sql', nodegroup_access(m))):
        with open(os.path.join(args.out, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(lines))
        print(name)
    return 0


if __name__ == '__main__':
    sys.exit(main())
