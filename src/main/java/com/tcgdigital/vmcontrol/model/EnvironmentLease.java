package com.tcgdigital.vmcontrol.model;

import jakarta.persistence.*;

import java.sql.Timestamp;

/**
 * An environment lease (E15): a running, opted-in environment has an end time, after which the
 * platform stops it. At most one ACTIVE lease per environment (unique index on the generated
 * active_environment_id, V42).
 */
@Entity
@Table(name = "environment_lease")
public class EnvironmentLease {

    @Id
    @Column(name = "lease_id", length = 36)
    private String leaseId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "environment_id", nullable = false)
    private Environment environment;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private LeaseStatus status;

    @Enumerated(EnumType.STRING)
    @Column(name = "source", nullable = false, length = 20)
    private LeaseSource source;

    @Column(name = "lock_id", length = 36)
    private String lockId;

    @Column(name = "started_by_user_id", nullable = false, length = 36)
    private String startedByUserId;

    @Column(name = "started_at", nullable = false)
    private Timestamp startedAt;

    @Column(name = "ends_at", nullable = false)
    private Timestamp endsAt;

    @Column(name = "ended_at")
    private Timestamp endedAt;

    @Column(name = "end_reason", length = 255)
    private String endReason;

    @Column(name = "extended_minutes_total", nullable = false)
    private int extendedMinutesTotal;

    @Column(name = "stop_execution_id", length = 36)
    private String stopExecutionId;

    @Column(name = "stop_attempts", nullable = false)
    private int stopAttempts;

    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    /** Generated by the database (V42): the environment id while ACTIVE; never written here. */
    @Column(name = "active_environment_id", length = 36, insertable = false, updatable = false)
    private String activeEnvironmentId;

    public EnvironmentLease() {
    }

    public String getLeaseId() { return leaseId; }
    public void setLeaseId(String leaseId) { this.leaseId = leaseId; }
    public Environment getEnvironment() { return environment; }
    public void setEnvironment(Environment environment) { this.environment = environment; }
    public LeaseStatus getStatus() { return status; }
    public void setStatus(LeaseStatus status) { this.status = status; }
    public LeaseSource getSource() { return source; }
    public void setSource(LeaseSource source) { this.source = source; }
    public String getLockId() { return lockId; }
    public void setLockId(String lockId) { this.lockId = lockId; }
    public String getStartedByUserId() { return startedByUserId; }
    public void setStartedByUserId(String startedByUserId) { this.startedByUserId = startedByUserId; }
    public Timestamp getStartedAt() { return startedAt; }
    public void setStartedAt(Timestamp startedAt) { this.startedAt = startedAt; }
    public Timestamp getEndsAt() { return endsAt; }
    public void setEndsAt(Timestamp endsAt) { this.endsAt = endsAt; }
    public Timestamp getEndedAt() { return endedAt; }
    public void setEndedAt(Timestamp endedAt) { this.endedAt = endedAt; }
    public String getEndReason() { return endReason; }
    public void setEndReason(String endReason) { this.endReason = endReason; }
    public int getExtendedMinutesTotal() { return extendedMinutesTotal; }
    public void setExtendedMinutesTotal(int extendedMinutesTotal) { this.extendedMinutesTotal = extendedMinutesTotal; }
    public String getStopExecutionId() { return stopExecutionId; }
    public void setStopExecutionId(String stopExecutionId) { this.stopExecutionId = stopExecutionId; }
    public int getStopAttempts() { return stopAttempts; }
    public void setStopAttempts(int stopAttempts) { this.stopAttempts = stopAttempts; }
    public Long getVersion() { return version; }
    public String getActiveEnvironmentId() { return activeEnvironmentId; }
}
