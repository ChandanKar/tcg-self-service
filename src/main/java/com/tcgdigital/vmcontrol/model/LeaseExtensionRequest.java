package com.tcgdigital.vmcontrol.model;

import jakarta.persistence.*;

import java.sql.Timestamp;

/** A request to extend a lease beyond the environment's maximum, decided by an owner (E15-T04). */
@Entity
@Table(name = "lease_extension_request")
public class LeaseExtensionRequest {

    @Id
    @Column(name = "request_id", length = 36)
    private String requestId;

    @Column(name = "lease_id", nullable = false, length = 36)
    private String leaseId;

    @Column(name = "requester_user_id", nullable = false, length = 36)
    private String requesterUserId;

    @Column(name = "minutes", nullable = false)
    private int minutes;

    @Column(name = "reason", length = 500)
    private String reason;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private LeaseExtensionStatus status;

    @Column(name = "reviewed_by_user_id", length = 36)
    private String reviewedByUserId;

    @Column(name = "reviewed_at")
    private Timestamp reviewedAt;

    @Column(name = "review_notes", length = 500)
    private String reviewNotes;

    @Column(name = "created_at", nullable = false)
    private Timestamp createdAt;

    /** Generated by the database (V43): the lease id while PENDING; never written here. */
    @Column(name = "pending_lease_id", length = 36, insertable = false, updatable = false)
    private String pendingLeaseId;

    public String getRequestId() { return requestId; }
    public void setRequestId(String requestId) { this.requestId = requestId; }
    public String getLeaseId() { return leaseId; }
    public void setLeaseId(String leaseId) { this.leaseId = leaseId; }
    public String getRequesterUserId() { return requesterUserId; }
    public void setRequesterUserId(String requesterUserId) { this.requesterUserId = requesterUserId; }
    public int getMinutes() { return minutes; }
    public void setMinutes(int minutes) { this.minutes = minutes; }
    public String getReason() { return reason; }
    public void setReason(String reason) { this.reason = reason; }
    public LeaseExtensionStatus getStatus() { return status; }
    public void setStatus(LeaseExtensionStatus status) { this.status = status; }
    public String getReviewedByUserId() { return reviewedByUserId; }
    public void setReviewedByUserId(String reviewedByUserId) { this.reviewedByUserId = reviewedByUserId; }
    public Timestamp getReviewedAt() { return reviewedAt; }
    public void setReviewedAt(Timestamp reviewedAt) { this.reviewedAt = reviewedAt; }
    public String getReviewNotes() { return reviewNotes; }
    public void setReviewNotes(String reviewNotes) { this.reviewNotes = reviewNotes; }
    public Timestamp getCreatedAt() { return createdAt; }
    public void setCreatedAt(Timestamp createdAt) { this.createdAt = createdAt; }
}
